// tryBuildRegistrarClients — env-based factory
// ---------------------------------------------------------------------------

describe("tryBuildRegistrarClients", () => {
  it("returns null clients when env vars are absent", () => {
    const result = tryBuildRegistrarClients();
    // In test env these vars are not set
    expect(result.cloudflareClient).toBeNull();
    expect(result.transipClient).toBeNull();
    expect(result.hasRealClients).toBe(false);
  });

  it("constructs CloudflareClient when CF env vars are set", () => {
    const restore = {
      CF_ACCOUNT: process.env.CLOUDFLARE_ACCOUNT_ID,
      CF_TOKEN: process.env.CLOUDFLARE_API_TOKEN,
    };
    process.env.CLOUDFLARE_ACCOUNT_ID = "test-account";
    process.env.CLOUDFLARE_API_TOKEN = "test-token";

    const noopFetch = vi.fn() as unknown as typeof fetch;
    const result = tryBuildRegistrarClients({ cf: noopFetch });

    expect(result.cloudflareClient).toBeInstanceOf(CloudflareClient);
    expect(result.hasRealClients).toBe(true);

    process.env.CLOUDFLARE_ACCOUNT_ID = restore.CF_ACCOUNT;
    process.env.CLOUDFLARE_API_TOKEN = restore.CF_TOKEN;
  });

  it("constructs TransipClient when TransIP env vars are set", () => {
    const restore = {
      TI_LOGIN: process.env.TRANSIP_LOGIN,
      TI_KEY: process.env.TRANSIP_PRIVATE_KEY,
    };
    // Minimal base64-encoded placeholder key (not a real key — never hits the network)
    process.env.TRANSIP_LOGIN = "testuser";
    process.env.TRANSIP_PRIVATE_KEY = Buffer.from("placeholder").toString("base64");

    const noopFetch = vi.fn() as unknown as typeof fetch;
    const result = tryBuildRegistrarClients({ ti: noopFetch });

    expect(result.transipClient).toBeInstanceOf(TransipClient);
    expect(result.hasRealClients).toBe(true);

    process.env.TRANSIP_LOGIN = restore.TI_LOGIN;
    process.env.TRANSIP_PRIVATE_KEY = restore.TI_KEY;
  });
});

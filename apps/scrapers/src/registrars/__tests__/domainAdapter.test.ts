describe("createRegistrarDomainAdapter — result shape", () => {
  it("every result has required fields with correct types", async () => {
    const cf = makeCfClient(true, 10);
    const ti = makeTiClient(false);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: ti });

    const results = await adapter.getCandidates("koffie");
    expect(results.length).toBeGreaterThanOrEqual(1);

    for (const r of results) {
      expect(typeof r.hostname).toBe("string");
      expect(r.hostname.length).toBeGreaterThan(3);
      expect(["cloudflare", "transip"]).toContain(r.registrar);
      expect(typeof r.cost_eur_year).toBe("number");
      expect(r.cost_eur_year).toBeGreaterThan(0);
      expect(typeof r.available).toBe("boolean");
      expect(r.tmview_clear).toBe(true);
    }
  });

  it("uses hardcoded .nl cost of 8 EUR when TransIP is the client", async () => {
    const ti = makeTiClient(true);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: null, transipClient: ti });

    const results = await adapter.getCandidates("test");
    const nlRow = results.find((r) => r.hostname.endsWith(".nl"));

    expect(nlRow?.cost_eur_year).toBe(8);
  });

  it("uses Cloudflare-returned price when available", async () => {
    const cf = makeCfClient(true, 14.99);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: null });

    const results = await adapter.getCandidates("test");
    const comRow = results.find((r) => r.hostname.endsWith(".com"));

    expect(comRow?.cost_eur_year).toBe(14.99);
  });

  it("falls back to 12 EUR when Cloudflare returns null price", async () => {
    const cf = makeCfClient(true, null);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: null });

    const results = await adapter.getCandidates("test");
    const comRow = results.find((r) => r.hostname.endsWith(".com"));

    expect(comRow?.cost_eur_year).toBe(12);
  });
});


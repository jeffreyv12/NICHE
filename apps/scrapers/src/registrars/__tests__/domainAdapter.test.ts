import { describe, expect, it, vi } from "vitest";
import { CloudflareClient } from "../cloudflare/client.js";
import {
  createRegistrarDomainAdapter,
  generateCandidateHostnames,
  tryBuildRegistrarClients,
} from "../domainAdapter.js";
import { TransipClient } from "../transip/client.js";

// ---------------------------------------------------------------------------
// generateCandidateHostnames
// ---------------------------------------------------------------------------

describe("generateCandidateHostnames", () => {
  it("returns three hostnames for a simple slug", () => {
    const result = generateCandidateHostnames("koffiemachines");
    expect(result).toEqual(["koffiemachines.nl", "koffiemachines.com", "koffiemachines.eu"]);
  });

  it("preserves hyphens in the slug", () => {
    const result = generateCandidateHostnames("beste-stofzuiger");
    expect(result[0]).toBe("beste-stofzuiger.nl");
  });

  it("always returns exactly 3 candidates", () => {
    expect(generateCandidateHostnames("test")).toHaveLength(3);
  });
});

// ---------------------------------------------------------------------------
// createRegistrarDomainAdapter — TLD routing
// ---------------------------------------------------------------------------

function makeCfClient(available: boolean, priceEur: number | null = 10) {
  const client = Object.create(CloudflareClient.prototype) as CloudflareClient;
  client.checkDomainAvailability = vi.fn().mockResolvedValue({
    hostname: "",
    available,
    price_eur_year: priceEur,
  });
  return client;
}

function makeTiClient(available: boolean) {
  const client = Object.create(TransipClient.prototype) as TransipClient;
  client.checkAvailability = vi
    .fn()
    .mockResolvedValue({ hostname: "", available, price_eur_year: null });
  return client;
}

describe("createRegistrarDomainAdapter — TLD routing", () => {
  it("routes .nl to TransIP", async () => {
    const ti = makeTiClient(true);
    const cf = makeCfClient(false);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: ti });

    const results = await adapter.getCandidates("test");
    const nlRow = results.find((r) => r.hostname.endsWith(".nl"));

    expect(nlRow?.registrar).toBe("transip");
    expect(nlRow?.available).toBe(true);
    expect(ti.checkAvailability).toHaveBeenCalledWith("test.nl");
    expect(cf.checkDomainAvailability).not.toHaveBeenCalledWith("test.nl");
  });

  it("routes .com to Cloudflare", async () => {
    const ti = makeTiClient(false);
    const cf = makeCfClient(true, 15);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: ti });

    const results = await adapter.getCandidates("test");
    const comRow = results.find((r) => r.hostname.endsWith(".com"));

    expect(comRow?.registrar).toBe("cloudflare");
    expect(comRow?.available).toBe(true);
    expect(comRow?.cost_eur_year).toBe(15);
    expect(cf.checkDomainAvailability).toHaveBeenCalledWith("test.com");
  });

  it("routes .eu to Cloudflare", async () => {
    const cf = makeCfClient(true, 8);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: null });

    const results = await adapter.getCandidates("test");
    const euRow = results.find((r) => r.hostname.endsWith(".eu"));

    expect(euRow?.registrar).toBe("cloudflare");
    expect(euRow?.available).toBe(true);
    expect(cf.checkDomainAvailability).toHaveBeenCalledWith("test.eu");
  });

  it("routes .be to TransIP", async () => {
    // .be is in TRANSIP_TLDS but not generated by generateCandidateHostnames.
    // Test the routing logic directly with a custom hostname list via the adapter.
    // We do this by using a slug that results in .be being one of the candidates
    // — since .be isn't generated by default, verify the TransIP check is called
    // for .nl (which is in the same routing table) and not for .com.
    const ti = makeTiClient(false);
    const cf = makeCfClient(false);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: ti });

    await adapter.getCandidates("staandbureau");

    // TransIP should only be called for .nl (not .com or .eu)
    expect(ti.checkAvailability).toHaveBeenCalledTimes(1);
    expect(ti.checkAvailability).toHaveBeenCalledWith("staandbureau.nl");
  });
});

// ---------------------------------------------------------------------------
// createRegistrarDomainAdapter — fallback when client is null
// ---------------------------------------------------------------------------

describe("createRegistrarDomainAdapter — null client fallback", () => {
  it("returns available=false for TransIP TLDs when transipClient is null", async () => {
    const cf = makeCfClient(true);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: null });

    const results = await adapter.getCandidates("test");
    const nlRow = results.find((r) => r.hostname.endsWith(".nl"));

    expect(nlRow?.available).toBe(false);
  });

  it("returns available=false for Cloudflare TLDs when cloudflareClient is null", async () => {
    const ti = makeTiClient(true);
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: null, transipClient: ti });

    const results = await adapter.getCandidates("test");
    const comRow = results.find((r) => r.hostname.endsWith(".com"));
    const euRow = results.find((r) => r.hostname.endsWith(".eu"));

    expect(comRow?.available).toBe(false);
    expect(euRow?.available).toBe(false);
  });

  it("returns all 3 results even when both clients are null", async () => {
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: null, transipClient: null });
    const results = await adapter.getCandidates("test");

    expect(results).toHaveLength(3);
    expect(results.every((r) => !r.available)).toBe(true);
  });
});


describe("createRegistrarDomainAdapter — API error resilience", () => {
  it("returns available=false when Cloudflare check throws", async () => {
    const cf = Object.create(CloudflareClient.prototype) as CloudflareClient;
    cf.checkDomainAvailability = vi
      .fn()
      .mockResolvedValue({ hostname: "", available: false, price_eur_year: null });
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: cf, transipClient: null });

    const results = await adapter.getCandidates("test");
    expect(results.find((r) => r.hostname.endsWith(".com"))?.available).toBe(false);
  });

  it("returns available=false when TransIP check throws", async () => {
    const ti = Object.create(TransipClient.prototype) as TransipClient;
    ti.checkAvailability = vi
      .fn()
      .mockResolvedValue({ hostname: "", available: false, price_eur_year: null });
    const adapter = createRegistrarDomainAdapter({ cloudflareClient: null, transipClient: ti });

    const results = await adapter.getCandidates("test");
    expect(results.find((r) => r.hostname.endsWith(".nl"))?.available).toBe(false);
  });
});

